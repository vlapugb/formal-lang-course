"""Context-free path queries using sparse Boolean matrix multiplication.

This module implements the Boolean matrix formulation of context-free path
querying. For each grammar variable ``A``, ``T[A]`` is an ``n x n`` Boolean CSR
matrix: ``T[A][i, j]`` is true when some path from ``i`` to ``j`` spells a word
derived from ``A``.

The algorithm has three stages:

1. Terminal rules ``A -> a`` initialize ``T[A]`` from matching graph edges.
2. Epsilon rules ``A -> epsilon`` add the identity matrix to ``T[A]``.
3. Every binary rule ``A -> B C`` contributes ``T[B] @ T[C]`` to ``T[A]``.
   Rules are revisited only while at least one operand changed in the
   previous round, stopping when no matrix gains a true entry.

The products are ordinary sparse Boolean matrix multiplications. Tensor
products are not used here.
"""

from collections import defaultdict

from networkx import DiGraph
from pyformlang.cfg import CFG
from scipy.sparse import csr_matrix, eye

from project.weak_normal_form import cfg_to_weak_normal_form


def matrix_based_cfpq(
    cfg: CFG,
    graph: DiGraph,
    start_nodes: set[int] | None = None,
    final_nodes: set[int] | None = None,
) -> set[tuple[int, int]]:
    """Return endpoint pairs whose connecting paths are generated by ``cfg``.

    The grammar is converted to weak Chomsky normal form first. ``None`` or an
    empty start/final set selects all graph vertices; unknown boundary vertices
    raise ``ValueError``. All vertices remain available as intermediate
    vertices, and epsilon paths are included at every vertex. Binary rules are
    revisited only while one of their operand matrices changed in the previous
    round. The input grammar, graph, and caller-provided boundary sets are not
    modified.
    """
    grammar = cfg_to_weak_normal_form(cfg)
    nodes = list(graph.nodes)
    node_indices = {node: index for index, node in enumerate(nodes)}
    node_set = set(nodes)
    starts = set(start_nodes) if start_nodes else node_set
    finals = set(final_nodes) if final_nodes else node_set
    if not (starts | finals) <= node_set:
        raise ValueError("Start and final states must be graph vertices")

    size = len(nodes)
    matrices = {
        variable: csr_matrix((size, size), dtype=bool)
        for variable in grammar.variables | {grammar.start_symbol}
    }

    terminal_rules = defaultdict(list)
    epsilon_variables = []
    binary_rules = []
    for production in grammar.productions:
        body = production.body
        if not body:
            epsilon_variables.append(production.head)
        elif len(body) == 1:
            terminal_rules[body[0].value].append(production.head)
        elif len(body) == 2:
            binary_rules.append((production.head, body[0], body[1]))
        else:
            raise ValueError("Grammar is not in weak Chomsky normal form")

    edge_rows = defaultdict(list)
    edge_columns = defaultdict(list)
    for source, target, data in graph.edges(data=True):
        label = data["label"]
        edge_rows[label].append(node_indices[source])
        edge_columns[label].append(node_indices[target])

    for label, rows in edge_rows.items():
        heads = terminal_rules.get(label)
        if not heads:
            continue
        edge_matrix = csr_matrix(
            ([True] * len(rows), (rows, edge_columns[label])),
            shape=(size, size),
            dtype=bool,
        )
        for head in heads:
            matrices[head] = matrices[head].maximum(edge_matrix)

    if epsilon_variables:
        identity = eye(size, format="csr", dtype=bool)
        for variable in epsilon_variables:
            matrices[variable] = matrices[variable].maximum(identity)

    binary_by_body = defaultdict(list)
    for head, left, right in binary_rules:
        binary_by_body[(left, right)].append(head)

    changed_vars = {variable for variable, matrix in matrices.items() if matrix.nnz}
    while changed_vars:
        next_changed = set()
        for (left, right), heads in binary_by_body.items():
            if left not in changed_vars and right not in changed_vars:
                continue
            if matrices[left].nnz == 0 or matrices[right].nnz == 0:
                continue
            product = matrices[left] @ matrices[right]
            if product.nnz == 0:
                continue
            for head in heads:
                current = matrices[head]
                updated = current.maximum(product)
                if updated.nnz != current.nnz:
                    matrices[head] = updated
                    next_changed.add(head)
        changed_vars = next_changed

    rows, columns = matrices[grammar.start_symbol].nonzero()
    return {
        (nodes[row], nodes[column])
        for row, column in zip(rows, columns)
        if nodes[row] in starts and nodes[column] in finals
    }
